"""Generate TypeScript shapes and compile-time examples from C02's Python source."""

import argparse
import json
from pathlib import Path

from pydantic.json_schema import models_json_schema

from backend.contracts import MODEL_TYPES


def render_type(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(v, ensure_ascii=False) for v in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(render_type(part) for part in schema["anyOf"])
    kind = schema.get("type")
    if kind in {"string", "boolean", "null"}:
        return kind
    if kind in {"integer", "number"}:
        if "minimum" in schema and schema["minimum"] == schema.get("maximum"):
            return json.dumps(schema["minimum"])
        return "number"
    if kind == "array":
        return f"Array<{render_type(schema['items'])}>"
    if kind == "object":
        patterns = schema.get("patternProperties", {})
        if len(patterns) == 1 and "properties" not in schema:
            return f"Record<string, {render_type(next(iter(patterns.values())))}>"
        if "properties" not in schema and isinstance(schema.get("additionalProperties"), dict):
            return f"Record<string, {render_type(schema['additionalProperties'])}>"
        if "properties" in schema and schema.get("additionalProperties") is False:
            required = schema.get("required", [])
            fields = [f"  {json.dumps(name)}{'' if name in required else '?'}: {render_type(value)};"
                      for name, value in schema["properties"].items()]
            return "{\n" + "\n".join(fields) + "\n}"
    raise ValueError(f"Unsupported JSON Schema shape: {schema}")


def generated_files(root):
    _, schema = models_json_schema([(model, "validation") for model in MODEL_TYPES.values()])
    header = "// Generated by python -m tools.export_contracts. Do not edit.\n"
    header += "// Static shapes only: bounds, references, and runtime semantics are checked by Python.\n\n"
    types = header + "\n\n".join(
        f"export type {name} = {render_type(definition)};"
        for name, definition in sorted(schema["$defs"].items())
    ) + "\n"
    samples = json.loads((root / "data/contracts/valid.json").read_text())
    samples["building"] = {"model": "Building", "payload": json.loads((root / "data/fixtures/two-route-v1.json").read_text())}
    examples = header + 'import type * as Contracts from "./types.generated";\n\n'
    for name, item in samples.items():
        payload = json.dumps(item["payload"], ensure_ascii=False, indent=2)
        examples += f"export const {name} = {payload} satisfies Contracts.{item['model']};\n\n"
    return {root / "contracts/types.generated.ts": types, root / "contracts/samples.generated.ts": examples.rstrip() + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated files differ; do not overwrite")
    args = parser.parse_args()
    stale = []
    root = Path(__file__).resolve().parents[1]
    for path, content in generated_files(root).items():
        if args.check:
            if not path.exists() or path.read_text() != content: stale.append(str(path.relative_to(root)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        print("Regenerate contracts: " + ", ".join(stale))
        return 1
    print("Contract exports match." if args.check else "Contract exports generated.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
